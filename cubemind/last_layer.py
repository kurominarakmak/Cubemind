"""Exact ZBLL recognition and replay-verified algorithm lookup."""

import json
from functools import lru_cache
from pathlib import Path

from cubemind.environment.cube import (
    SOLVED_STATE,
    apply_sequence,
    f2l_complete,
    inverse_sequence,
    last_layer_edges_oriented,
    normalize_cube_orientation,
    parse_moves,
)

ROOT = Path(__file__).resolve().parents[1]
ZBLL_PATH = ROOT / "data" / "algorithms" / "zbll_cases.json"


def _canonical_key(state):
    oriented = normalize_cube_orientation(state)
    return min(bytes(apply_sequence(oriented, ["U"] * turns)) for turns in range(4))


@lru_cache(maxsize=1)
def _case_index():
    database = json.loads(ZBLL_PATH.read_text(encoding="utf-8"))
    by_key = {}
    by_id = {}
    for case in database["cases"]:
        algorithm = case["algorithms"][0]
        state = tuple(apply_sequence(SOLVED_STATE, inverse_sequence(algorithm)))
        normalized = normalize_cube_orientation(state)
        if not f2l_complete(normalized) or not last_layer_edges_oriented(normalized):
            raise ValueError("{} does not define an eligible ZBLL case".format(case["case_id"]))
        key = _canonical_key(state)
        if key in by_key:
            raise ValueError("ZBLL case identity collision: {} and {}".format(by_key[key]["case_id"], case["case_id"]))
        by_key[key] = case
        by_id[case["case_id"]] = (case, state)
    if len(by_id) != 493:
        raise ValueError("Expected 493 ZBLL cases including PLL; found {}".format(len(by_id)))
    return by_key, by_id


def recognize_zbll_case(state):
    """Return the exact database case ID, or None when the state is ineligible/unknown."""
    normalized = normalize_cube_orientation(state)
    if not f2l_complete(normalized) or not last_layer_edges_oriented(normalized):
        return None
    case = _case_index()[0].get(_canonical_key(normalized))
    return case["case_id"] if case else None


def zbll_case_state(case_id):
    """Return a replay-verified representative generated by inverting its primary alg."""
    try:
        return _case_index()[1][case_id][1]
    except KeyError:
        raise ValueError("Unknown ZBLL case: {}".format(case_id))


def solution_for_zbll_state(state, case_id=None):
    """Return a verified algorithm plus setup moves for this orientation/AUF of a case."""
    state = tuple(state)
    case_id = case_id or recognize_zbll_case(state)
    if case_id is None:
        return None
    case, representative = _case_index()[1][case_id]
    if recognize_zbll_case(state) != case_id:
        return None
    algorithm = parse_moves(case["algorithms"][0])
    rotations = _rotation_paths()
    for auf in ([], ["U"], ["U2"], ["U'"]):
        for rotation in rotations:
            setup = tuple(auf) + rotation
            if apply_sequence(representative, setup) == state:
                solution = inverse_sequence(setup) + algorithm
                if normalize_cube_orientation(apply_sequence(state, solution)) == SOLVED_STATE:
                    return solution
    return None


@lru_cache(maxsize=1)
def _rotation_paths():
    from collections import deque

    from cubemind.environment.cube import apply_move

    centers = tuple(face * 9 + 4 for face in range(6))
    start = SOLVED_STATE
    paths = {tuple(start[index] for index in centers): ()}
    queue = deque([start])
    moves = ("x", "x'", "x2", "y", "y'", "y2", "z", "z'", "z2")
    while queue:
        current = queue.popleft()
        path = paths[tuple(current[index] for index in centers)]
        for move in moves:
            next_state = apply_move(current, move)
            key = tuple(next_state[index] for index in centers)
            if key not in paths:
                paths[key] = path + (move,)
                queue.append(next_state)
    return tuple(paths.values())


def verify_zbll_database():
    """Assert case coverage, unique AUF/orientation identities, and primary-alg replay."""
    _case_index()
    database = json.loads(ZBLL_PATH.read_text(encoding="utf-8"))
    for case in database["cases"]:
        state = zbll_case_state(case["case_id"])
        for algorithm in case["algorithms"]:
            parse_moves(algorithm)
            solved = False
            for pre_auf in ([], ["U"], ["U2"], ["U'"]):
                for post_auf in ([], ["U"], ["U2"], ["U'"]):
                    result = apply_sequence(apply_sequence(state, pre_auf), algorithm)
                    result = normalize_cube_orientation(apply_sequence(result, post_auf))
                    if result == SOLVED_STATE:
                        solved = True
                        break
                if solved:
                    break
            if not solved:
                raise ValueError("Unverified algorithm in {}: {}".format(case["case_id"], algorithm))
    return {"cases": len(database["cases"]),
            "algorithms": sum(len(case["algorithms"]) for case in database["cases"]),
            "recognition": "exact AUF- and orientation-normalized facelet signature"}
